export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setCurrentLanguage] = useState<Language>(readStoredLanguage);
  const setLanguage = useCallback((next: Language) => {
    setCurrentLanguage(next);
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
    } catch {
      // Keep the current session language if storage is unavailable.
    }
  }, []);
  const t = useCallback((text: string, values?: TranslationValues) => translate(language, text, values), [language]);
  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

// eslint-disable-next-line react-refresh/only-export-components
export function useLanguage(): LanguageContextValue {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useLanguage must be used within LanguageProvider");
  return value;
}

export function LocalizedText({ text }: { text: string }) {
  const { language } = useLanguage();
  const leading = text.match(/^\s*/)?.[0] ?? "";
  const trailing = text.match(/\s*$/)?.[0] ?? "";
  return <>{leading}{translate(language, text)}{trailing}</>;
}
