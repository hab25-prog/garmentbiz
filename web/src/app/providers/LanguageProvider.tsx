function interpolate(text: string, values?: TranslationValues): string {
  if (!values) return text;
  return text.replace(/\{([A-Za-z0-9_]+)\}/g, (placeholder, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : placeholder,
  );
}

// eslint-disable-next-line react-refresh/only-export-components
export function isLanguage(value: unknown): value is Language {
  return value === "en" || value === "am";
}

function readStoredLanguage(): Language {
  try {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return isLanguage(stored) ? stored : "en";
  } catch {
    return "en";
  }
}

// eslint-disable-next-line react-refresh/only-export-components
export function translate(language: Language, text: string, values?: TranslationValues): string {
  const normalized = text.replace(/\s+/g, " ").trim();
  const translated = language === "am" ? amharic[normalized] ?? normalized : english[normalized] ?? normalized;
  return interpolate(translated, values);
}

// eslint-disable-next-line react-refresh/only-export-components
export function translateCurrent(text: string, values?: TranslationValues): string {
  let language: Language = "en";
  try {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (isLanguage(stored)) language = stored;
  } catch {
    // The UI remains usable in English when browser storage is unavailable.
  }
  return translate(language, text, values);
}

